import assert from "node:assert/strict";
import fs from "node:fs";
import { after, before, test } from "node:test";

// RPL-064 SQL 통합 테스트. 로컬 일회용 PostgreSQL에서만 실행한다. CI·운영 DB에서는 실행하지 않는다.
//   LEDGER_IT_DATABASE_URL=postgres://postgres@localhost:5433/rp_it \
//     node --import tsx --test test/integration/ledger-import.it.ts
const target = process.env.LEDGER_IT_DATABASE_URL ?? "";
if (!/^postgres(ql)?:\/\/[^@]*@(localhost|127\.0\.0\.1)[:/]/.test(target)) {
  throw new Error("LEDGER_IT_DATABASE_URL must point to a local throwaway database");
}
process.env.DATABASE_URL = target;

import { queryDb } from "../../lib/db";
import { importLedgerItems } from "../../lib/ledger-import-store";
import { validateLedgerImport } from "../../lib/ledger-import-validate";
import { toImportItems } from "../../lib/ledger-import";
import { diagnoseLedger } from "../../lib/ledger-diagnosis";
import { PERSONA_SAMPLES } from "../../lib/ledger-samples";
import { loadWorkspace } from "../../lib/workspace-data";
import { computeLedgerAlerts } from "../../lib/ledger-alerts";

const TODAY = "2026-11-21";
const OWNER_A = "00000000-0000-0000-0000-00000000000a";
const OWNER_B = "00000000-0000-0000-0000-00000000000b";

before(async () => {
  // 운영 스키마 전체가 아니라 이 테스트에 필요한 테이블만 만든다.
  await queryDb(`create table if not exists public.campaigns (
    id bigint generated by default as identity primary key,
    title text, platform text, link text, reward text, region text, deadline_at timestamptz,
    cash_fee_amount integer, provided_value_amount integer, points_amount integer, reimbursement_amount integer
  )`);
  for (const file of [
    "20260929_user_campaigns",
    "20260929_user_campaign_settlements",
    "20260929_user_campaign_tasks",
    "20261121_ledger_tracking",
  ]) {
    await queryDb(fs.readFileSync(`db/migrations/${file}.sql`, "utf8"));
  }
});

after(async () => {
  const g = globalThis as { rePlacePool?: { end: () => Promise<void> } };
  await g.rePlacePool?.end();
});

for (const persona of PERSONA_SAMPLES) {
  test(`${persona.id}: import then workspace alerts match the free check`, async () => {
    const owner = persona.id === "small-seller" ? OWNER_B : OWNER_A;
    await queryDb("delete from user_campaign_records where auth_user_id = $1", [owner]);
    const diagnosis = diagnoseLedger(persona.build(TODAY), TODAY);
    assert.ok(diagnosis.ok);
    if (!diagnosis.ok) return;
    const validation = validateLedgerImport({ items: toImportItems(diagnosis.rows) });
    assert.ok(validation.ok);
    if (!validation.ok) return;

    const created = await importLedgerItems(owner, validation.items);
    assert.equal(created.records.length, diagnosis.rows.length);

    const workspace = await loadWorkspace(owner);
    assert.equal(workspace.records.length, diagnosis.rows.length);
    // 응답으로 돌려준 항목이 다시 읽은 workspace와 같은 모양인지 확인한다.
    for (const record of created.records) {
      const loaded = workspace.records.find((r) => r.id === record.id)!;
      assert.deepEqual({ ...record }, { ...loaded });
    }
    for (const task of created.tasks) {
      const loaded = workspace.tasks.find((t) => t.id === task.id)!;
      assert.deepEqual({ ...task }, { ...loaded });
    }
    for (const settlement of created.settlements) {
      const loaded = workspace.settlements.find((s) => s.record_id === settlement.record_id)!;
      assert.deepEqual({ ...settlement }, { ...loaded });
    }

    const alerts = computeLedgerAlerts(workspace.records, workspace.tasks, workspace.settlements, TODAY);
    console.log(persona.id, JSON.stringify({
      check: {
        overdueUnpublished: diagnosis.summary.overdueUnpublished,
        paymentOverdue: diagnosis.summary.paymentOverdue,
        overdueOutstanding: diagnosis.summary.overdueOutstanding,
      },
      workspace: {
        overdueUnpublished: alerts.overdueUnpublished,
        paymentOverdue: alerts.paymentOverdue,
        overdueOutstanding: alerts.overdueOutstanding,
        paymentUnscheduled: alerts.paymentUnscheduled,
      },
    }));
    assert.equal(alerts.overdueUnpublished, diagnosis.summary.overdueUnpublished);
    assert.equal(alerts.paymentOverdue, diagnosis.summary.paymentOverdue);
    assert.equal(alerts.overdueOutstanding, diagnosis.summary.overdueOutstanding);
  });
}

test("owners never see each other's imported rows", async () => {
  const a = await loadWorkspace(OWNER_A);
  const b = await loadWorkspace(OWNER_B);
  const aIds = new Set(a.records.map((r) => r.id));
  assert.ok(b.records.every((r) => !aIds.has(r.id)));
});

test("settlement PUT keeps cash_payment_due_at when the field is omitted", async () => {
  const source = fs.readFileSync("app/api/v1/me/settlements/[recordId]/route.ts", "utf8");
  const sql = /queryDb\(\s*`([\s\S]*?)`/.exec(source)![1];
  const { rows } = await queryDb<{ id: number }>(
    "select id from user_campaign_records where auth_user_id = $1 order by id limit 1",
    [OWNER_A],
  );
  const id = rows[0].id;
  const base = [OWNER_A, id, 1000, null, null, null, null, null, null, null, "memo"];
  await queryDb(sql, [...base, true, "2026-12-01T00:00:00.000Z"]);
  let r = await queryDb<{ d: string | null }>("select cash_payment_due_at::text d from user_campaign_settlements where record_id=$1", [id]);
  assert.match(r.rows[0].d ?? "", /^2026-12-01/);
  await queryDb(sql, [...base, false, null]);
  r = await queryDb<{ d: string | null }>("select cash_payment_due_at::text d from user_campaign_settlements where record_id=$1", [id]);
  assert.match(r.rows[0].d ?? "", /^2026-12-01/);
  await queryDb(sql, [...base, true, null]);
  r = await queryDb<{ d: string | null }>("select cash_payment_due_at::text d from user_campaign_settlements where record_id=$1", [id]);
  assert.equal(r.rows[0].d, null);
});

test("records PATCH sets and clears published_url and the DB rejects non-http URLs", async () => {
  const source = fs.readFileSync("app/api/v1/me/records/[id]/route.ts", "utf8");
  const sql = /queryDb\(\s*`(update[\s\S]*?)`/.exec(source)![1];
  const { rows } = await queryDb<{ id: number }>(
    "select id from user_campaign_records where auth_user_id = $1 order by id limit 1",
    [OWNER_A],
  );
  const id = rows[0].id;
  const res = await queryDb<{ published_url: string | null }>(sql, [OWNER_A, id, "completed", false, null, false, null, true, "https://blog.naver.com/x/1"]);
  assert.equal(res.rows[0].published_url, "https://blog.naver.com/x/1");
  const kept = await queryDb<{ published_url: string | null }>(sql, [OWNER_A, id, "completed", false, null, false, null, false, null]);
  assert.equal(kept.rows[0].published_url, "https://blog.naver.com/x/1");
  const wrongOwner = await queryDb(sql, [OWNER_B, id, "completed", false, null, false, null, true, null]);
  assert.equal(wrongOwner.rowCount, 0);
  await assert.rejects(
    queryDb("update user_campaign_records set published_url = 'javascript:alert(1)' where id = $1", [id]),
  );
});

test("a failing row rolls back the whole import", async () => {
  const before = await queryDb<{ n: string }>("select count(*) n from user_campaign_records where auth_user_id = $1", [OWNER_A]);
  await assert.rejects(
    importLedgerItems(OWNER_A, [
      { title: "ok", platform: null, status: "selected", deadlineAt: null, publishedUrl: null, expectedCashAmount: null, actualCashReceivedAmount: null, cashPaymentDueAt: null, note: null },
      { title: "bad", platform: null, status: "selected", deadlineAt: null, publishedUrl: "javascript:x", expectedCashAmount: null, actualCashReceivedAmount: null, cashPaymentDueAt: null, note: null },
    ]),
  );
  const afterCount = await queryDb<{ n: string }>("select count(*) n from user_campaign_records where auth_user_id = $1", [OWNER_A]);
  assert.equal(afterCount.rows[0].n, before.rows[0].n);
});
